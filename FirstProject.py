def какая_сейчас_пара():
    if weekday not in расписание:
        return "Сегодня пар нет."

    day_schedule = расписание[weekday]

    for номер, (начало, конец) in расписание_звонков.items():
        if начало <= current_time <= конец:
            пара = day_schedule.get(номер)

            if "Числитель" in пара and "Знаменатель" in пара:
                выбранная = пара["Числитель"] if is_numerator else пара["Знаменатель"]
                return (f"Сейчас {номер}-я пара ({тип_недели}): {выбранная['Пара']}, "
                        f"кабинет {выбранная['Кабинет']}, преподаватель {выбранная['Преподаватель']}.")
            else:
                return (f"Сейчас {номер}-я пара: {пара['Пара']}, "
                        f"кабинет {пара['Кабинет']}, преподаватель {пара['Преподаватель']}.")

    for номер, (начало, конец) in расписание_звонков.items():
        if начало > current_time and номер in day_schedule:
            пара = day_schedule[номер]
            if "Числитель" in пара and "Знаменатель" in пара:
                выбранная = пара["Числитель"] if is_numerator else пара["Знаменатель"]
            else:
                выбранная = пара
            return (f"Сейчас перемена. Следующая пара ({тип_недели}): {номер}-я — {выбранная['Пара']}, "
                    f"кабинет {выбранная['Кабинет']}. Начнётся в {начало.strftime('%H:%M')}.")

    return "На сегодня больше нет пар."

